# --------------------------------------------- TLS verification stays enforced

def test_certificate_from_an_untrusted_ca_is_rejected(stub, monkeypatch):
    original_adapter = rest_adapter._PinnedIPAdapter
    monkeypatch.setattr(rest_adapter, "_PinnedIPAdapter",
                        lambda hostname, address: original_adapter(hostname, address, stub.port))
    # no test-CA override here: the default (certifi) trust store must reject the stub's certificate
    with pytest.raises(PermanentSourceError, match="could not be verified"):
        _fetch_payload(f"https://{HOST}:{stub.port}/ok", HOST, "127.0.0.1", {}, 5, None)


def test_certificate_for_another_hostname_is_rejected_even_from_a_trusted_ca(fetch):
    with pytest.raises(PermanentSourceError, match="could not be verified"):
        fetch("/ok", hostname="wrong.example")  # trusted CA, but the certificate is for stub.example


def test_adapter_refuses_to_follow_a_changed_connection_target(stub):
    adapter = rest_adapter._PinnedIPAdapter(HOST, "127.0.0.1", stub.port)
    prepared = requests.Request("GET", f"https://attacker.example:{stub.port}/ok").prepare()
    with pytest.raises(requests.exceptions.InvalidURL):
        adapter.get_connection_with_tls_context(prepared, verify=True)
    prepared = requests.Request("GET", f"https://{HOST}:{stub.port + 7}/ok").prepare()
    with pytest.raises(requests.exceptions.InvalidURL):
        adapter.get_connection_with_tls_context(prepared, verify=True)
    adapter.close()
