"""HTTP_API transport tests over REAL sockets and TLS against a local stub server.

What this adds on top of test_rest_adapter.py (which mocks the transport): the actual requests/urllib3 stack, a real
TLS handshake with hostname verification, real timeouts, truncated and streamed bodies, and redirects.

Scope and honesty about what is *not* bypassed:
  * ``_fetch_payload`` is the lowest layer that talks to the network. The layer above it (``_safe_endpoint``:
    HTTPS on port 443 only, exact host allow-list, public-IP-only DNS answers) cannot target a loopback test server
    and is deliberately left untouched; test_rest_adapter.py covers it with a mocked resolver.
  * TLS verification stays ON. The tests only make the client trust a throwaway CA generated by ``trustme``;
    the "untrusted CA" and "wrong hostname" tests prove verification still rejects bad certificates.
  * The stub listens on 127.0.0.1 on an ephemeral port; nothing leaves the machine.
"""

from __future__ import annotations

import json
import ssl
import threading
import time
from collections import Counter
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from types import SimpleNamespace

import pytest
import requests
import trustme

import pidea_data.rest_adapter as rest_adapter
from pidea_data.rest_adapter import (
    MAX_PAGE_BYTES,
    PermanentSourceError,
    TransientSourceError,
    _fetch_payload,
)

HOST = "stub.example"
TOKEN = "stub-test-token-1234"


class Handler(BaseHTTPRequestHandler):
    def log_message(self, *args):  # keep test output quiet
        pass

    def _send(self, status, body=b"", content_type="application/json", headers=()):
        self.send_response(status)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(body)))
        for k, v in headers:
            self.send_header(k, v)
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):  # noqa: N802 - http.server API
        path = self.path.split("?")[0]
        self.server.hits[path] += 1
        if path == "/ok":
            self._send(200, json.dumps({"records": [{"id": 1, "amount": 12.5}], "has_more": False}).encode())
        elif path == "/echo-auth":
            self._send(200, json.dumps({"auth": self.headers.get("Authorization"),
                                        "host": self.headers.get("Host")}).encode())
        elif path.startswith("/status/"):
            self._send(int(path.rsplit("/", 1)[1]), b'{"error": "nope"}')
        elif path == "/redirect":
            self._send(302, b"", headers=[("Location", f"https://{HOST}:{self.server.server_port}/secret")])
        elif path == "/secret":
            self._send(200, b'{"records": [{"id": 666}]}')
        elif path == "/slow":
            time.sleep(3)
            self._send(200, b"[]")
        elif path == "/bad-json":
            self._send(200, b"{not json")
        elif path == "/wrong-type":
            self._send(200, b"<html>hi</html>", content_type="text/html")
        elif path == "/bad-gzip":
            self._send(200, b"this is not gzip", headers=[("Content-Encoding", "gzip")])
        elif path == "/declared-huge":  # advertises a huge body, sends none
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(MAX_PAGE_BYTES + 1))
            self.end_headers()
        elif path == "/streamed-huge":  # no Content-Length: body is read until close
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.end_headers()
            chunk = b" " * 65536
            try:
                for _ in range(MAX_PAGE_BYTES // 65536 + 8):
                    self.wfile.write(chunk)
            except OSError:
                pass  # client hung up once it hit its limit
        elif path == "/truncated":  # promises 100 bytes, sends 10, closes
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", "100")
            self.end_headers()
            self.wfile.write(b'{"records"')
        elif path == "/reset":  # accept the request, then drop the connection without a response
            self.connection.close()
        else:
            self._send(404, b"{}")


@pytest.fixture(scope="module")
def stub(tmp_path_factory):
    ca = trustme.CA()
    ca_file = tmp_path_factory.mktemp("tls") / "ca.pem"
    ca.cert_pem.write_to_path(str(ca_file))
    context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    ca.issue_cert(HOST).configure_cert(context)
    server = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
    server.socket = context.wrap_socket(server.socket, server_side=True)
    server.handle_error = lambda *args: None  # handshake failures are expected in the TLS tests
    server.hits = Counter()
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    yield SimpleNamespace(port=server.server_port, ca_file=str(ca_file), hits=server.hits)
    server.shutdown()
    server.server_close()


@pytest.fixture()
def fetch(stub, monkeypatch):
    """Call the real transport layer against the stub, trusting only the test CA (verification stays on)."""
    original_adapter = rest_adapter._PinnedIPAdapter
    monkeypatch.setattr(rest_adapter, "_PinnedIPAdapter",
                        lambda hostname, address: original_adapter(hostname, address, stub.port))
    original_get = requests.Session.get

    def get_with_test_ca(self, url, **kwargs):
        kwargs["verify"] = stub.ca_file
        return original_get(self, url, **kwargs)

    monkeypatch.setattr(requests.Session, "get", get_with_test_ca)
    stub.hits.clear()

    def _fetch(path, *, hostname=HOST, headers=None, timeout=5):
        url = f"https://{hostname}:{stub.port}{path}"
        return _fetch_payload(url, hostname, "127.0.0.1", headers or {"Accept": "application/json"}, timeout, None)
    return _fetch


# ------------------------------------------------------------------ success

def test_successful_json_response_over_real_tls(fetch):
    payload = fetch("/ok")
    assert payload["records"][0]["id"] == 1 and payload["has_more"] is False
    assert str(payload["records"][0]["amount"]) == "12.5"  # floats are parsed as Decimal


def test_bearer_header_is_sent_and_connection_is_pinned_with_the_original_host_header(fetch):
    echoed = fetch("/echo-auth", headers={"Authorization": f"Bearer {TOKEN}"})
    assert echoed["auth"] == f"Bearer {TOKEN}"
    assert echoed["host"] == HOST  # connected to 127.0.0.1 but presented the validated hostname


# --------------------------------------------------------- HTTP status codes

@pytest.mark.parametrize("status", [429, 500, 502, 503])
def test_transient_statuses_are_reported_once_without_hidden_retries(fetch, stub, status):
    with pytest.raises(TransientSourceError, match=str(status)):
        fetch(f"/status/{status}")
    assert stub.hits[f"/status/{status}"] == 1  # retry policy belongs to the worker, not the transport


@pytest.mark.parametrize("status", [400, 401, 403, 404])
def test_client_errors_are_permanent_and_not_retried(fetch, stub, status):
    with pytest.raises(PermanentSourceError, match=str(status)):
        fetch(f"/status/{status}")
    assert stub.hits[f"/status/{status}"] == 1


def test_errors_never_leak_the_bearer_token(fetch):
    for path in ("/status/500", "/status/401", "/bad-json", "/reset"):
        with pytest.raises((TransientSourceError, PermanentSourceError)) as excinfo:
            fetch(path, headers={"Authorization": f"Bearer {TOKEN}"})
        assert TOKEN not in str(excinfo.value)


# ------------------------------------------------------------------ redirects

def test_redirects_are_not_followed(fetch, stub):
    with pytest.raises(PermanentSourceError, match="302"):
        fetch("/redirect")
    assert stub.hits["/redirect"] == 1 and stub.hits["/secret"] == 0  # the redirect target was never requested


# ------------------------------------------------------- timeouts and drops

def test_slow_server_times_out_as_transient(fetch):
    started = time.monotonic()
    with pytest.raises(TransientSourceError, match="timed out"):
        fetch("/slow", timeout=1)
    assert time.monotonic() - started < 2.9  # gave up at the read timeout, did not wait for the response


def test_connection_dropped_before_a_response_is_transient(fetch):
    with pytest.raises(TransientSourceError):
        fetch("/reset")


def test_body_truncated_mid_stream_is_transient(fetch):
    with pytest.raises(TransientSourceError):
        fetch("/truncated")


def test_nothing_listening_is_transient(stub, monkeypatch):
    original_adapter = rest_adapter._PinnedIPAdapter
    dead_port = stub.port + 1 if stub.port < 65535 else stub.port - 1  # almost certainly closed
    monkeypatch.setattr(rest_adapter, "_PinnedIPAdapter",
                        lambda hostname, address: original_adapter(hostname, address, dead_port))
    with pytest.raises(TransientSourceError):
        _fetch_payload(f"https://{HOST}:{dead_port}/ok", HOST, "127.0.0.1", {}, 2, None)


